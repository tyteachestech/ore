import assert from 'node:assert/strict';
import {seed,ore,stamp} from './common.ts';
import {findAnnotation} from '../../packages/core/src/annotations.ts';
import {findCard} from '../../packages/core/src/cards.ts';
const {lib,item,card}=await seed('cause-controls');
const q=await ore('highlight',item.meta.id,'--exact','Retrieval makes the memory accessible.','--intent','question','--note','How?');
await ore('answer',q.id,'--text','First');
await Bun.sleep(3);
await ore('answer',q.id,'--text','Second');
const before=findAnnotation(lib,q.id).annotation.answers!;
assert.notEqual(before[0].ts,before[1].ts);
await ore('answer',q.id,'--edit',before[1].ts,'--text','Correct second');
assert.deepEqual(findAnnotation(lib,q.id).annotation.answers!.map(x=>x.text),['First','Correct second']);
console.log('[DEEP] distinct timestamps: second answer edited correctly; canonical annotation agrees');
const newStamp={vendor:'codex',model:'fixture-editor',prompt_version:'agent-fix@fixture'};
await ore('card','set',card.meta.id,'--question','Updated question','--ai',JSON.stringify(newStamp));
assert.deepEqual(findCard(lib,card.meta.id).meta.ai,newStamp);
console.log('[DEEP] --ai records replacement author in canonical exercise: PASS');
await ore('card','set',card.meta.id,'--question','Human edit','--ai','null');
assert.equal(findCard(lib,card.meta.id).meta.ai,undefined);
console.log('[DEEP] --ai null removes stamp in canonical exercise: PASS');
