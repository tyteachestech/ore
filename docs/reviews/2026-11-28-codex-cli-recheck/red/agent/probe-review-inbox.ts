import assert from 'node:assert/strict';
import {ore} from './common.ts';
import {commands} from '../../packages/cli/src/commands.ts';
import {resolve} from 'node:path';
process.env.ORE_LIBRARY=resolve('codex-out/agent/libs/guide-review');
let shown=await ore('card','show',(await ore('due'))[0].id,'--review');
assert.equal(shown.variant,'variant-ready');
console.log('[DEEP] remix on + two past passes + ready variant => selected');
await ore('goal','--remix','false');
shown=await ore('card','show',shown.id,'--review');
assert.equal(shown.variant,undefined);
console.log('[DEEP] remix off => original; eligible setting is honored by core');
process.env.ORE_LIBRARY=resolve('codex-out/agent/libs/inbox-retry');
let calls=0;
globalThis.fetch=async()=>{calls++; return new Response('Not found',{status:404});};
let r=await commands.inbox!.run([],{import:true});
assert.equal(calls,1); assert.equal(r.exitCode,0);
console.log('[DEEP] same failure: fetch attempted once, exit 0, waiting entry kept');
globalThis.fetch=async()=>{calls++; return new Response('Unavailable',{status:503});};
r=await commands.inbox!.run([],{import:true});
assert.equal(r.exitCode,1);
console.log('[DEEP] changing only HTTP error from 404 to 503: exit 1');
