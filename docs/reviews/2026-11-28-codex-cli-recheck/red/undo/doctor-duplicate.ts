import assert from 'node:assert/strict';
import {writeFileSync,readFileSync} from 'node:fs';
import {join} from 'node:path';
import {core,seed,artifact} from './common.ts';
import {commands} from '../../packages/cli/src/commands.ts';
const mode=process.argv[2]??'prefix';
const {lib,card}=await seed('duplicate-'+mode);
const copy=join(lib.root,'cards',mode.startsWith('prefix')?'000-copy-'+card.meta.id+'.md':card.meta.id+' copy.md');
writeFileSync(copy,readFileSync(card.path,'utf8').replace('What helps learning?','Which question is this?'));
if(mode==='prefix-reindex')core.rebuildIndex(lib);
const doctor=(await commands.doctor!.run([],{})).data as any;
const shown=(await commands.card!.run(['show',card.meta.id],{})).data as any;
const listed=(await commands.cards!.run([],{})).data as any[];
const index=core.openIndex(lib),indexed=index.cards();index.close();
const fixed=(await commands.doctor!.run([],{fix:true})).data;
const result={mode,doctor,fixed,showQuestion:shown.question,listQuestion:listed.find(c=>c.id===card.meta.id)?.question,indexQuestion:indexed.find(c=>c.id===card.meta.id)?.question};
console.log('[DEEP]',JSON.stringify(result));artifact('duplicate-'+mode+'.json',result);
assert.ok(doctor.issues.some((i:any)=>i.path===copy.slice(lib.root.length+1)),'Doctor must name the duplicate exercise file');
assert.equal(result.listQuestion,result.showQuestion,'List and open must agree which copy is canonical');
