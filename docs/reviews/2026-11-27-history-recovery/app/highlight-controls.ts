import assert from 'node:assert/strict';
import {setup,snap,git,rel,history,pinClock,advance,run} from './support';
import {addHighlight,readAnnotations} from '../../packages/core/src/annotations';
import {highlights} from '../../apps/desktop/src/highlights';
pinClock();
const {lib,item}=await setup('highlight-controls');
const first=addHighlight(item,{exact:'Retrieval practice means pulling an answer out of memory instead of reading it again.',intent:'keep',note:'Recovered note'});
const old=snap(lib);
const h=history();
const hl=highlights({run,show(){},landed(){},notify:h.notify,label:i=>i,page:()=>({off(){},on(){}}),unsaved:new Map()});
hl.read(readAnnotations(item),false);
advance();
const tmp=hl.standIn();
const exact='Each recall changes what is stored, so the next one comes easier.';
hl.create(['highlight',item.meta.id,'--exact',exact,'--intent','keep'],{...first,id:tmp,exact,note:'',rev:0},{saved(){},shown(){},failed(e){throw e;}});
assert.ok(hl.list().some(a=>a.id===tmp));
await hl.allSaved();await h.settle();
assert.equal(hl.list().length,2);
assert.ok(!hl.list().some(a=>a.id.startsWith('pending-')));
assert.notEqual(hl.idOf(tmp),tmp);
snap(lib);
git(lib,'restore','--source',old,'--',rel(lib,item.dir));
hl.read(readAnnotations(item),true,hl.reading());
assert.deepEqual(hl.list().map(a=>a.id),[first.id]);
assert.equal(hl.find(tmp),undefined);
assert.equal(hl.list()[0]!.note,'Recovered note');
console.log('PASS: landed stand-in disappears when restore removes its saved highlight; old highlight stays');
