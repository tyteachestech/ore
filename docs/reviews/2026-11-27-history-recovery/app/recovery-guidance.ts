import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {setup,snap,pinClock,git} from './support';
import {setNotes,getNotes} from '../../packages/core/src/notes';
pinClock();
const {lib,item}=await setup('recovery-guidance');
await setNotes(lib,item.meta.id,'Words to recover');const old=snap(lib);
await setNotes(lib,item.meta.id,'Accidental replacement');snap(lib);
const guide=readFileSync(`${lib.root}/AGENTS.md`,'utf8');
const skill=readFileSync('skills/ore/SKILL.md','utf8');
const template=readFileSync('packages/core/src/templates/library-agents.md','utf8');
assert.equal(guide,template);
assert.equal(git(lib,'show',`${old}:${getNotes(lib,item.meta.id).path}`),'Words to recover');
console.log('PASS: snapshot contains lost words; generated instructions match the template');
const {commands}=await import('../../packages/cli/src/commands');
console.log('library guide:',guide.split('\n').find(l=>l.startsWith('Never edit a library file')));
console.log('skill rule:',skill.split('\n').find(l=>l.includes('ore` is the only writer')));
const recovery=Object.keys(commands).filter(k=>/^(history|recover|restore)$/.test(k));
console.log('recovery commands:',JSON.stringify(recovery));
console.log('guide names snapshots or git recovery:',/snapshot|git (log|show|restore|checkout|revert|stash)/i.test(guide));
console.log('skill names snapshots or git recovery:',/snapshot|git (log|show|restore|checkout|revert|stash)/i.test(skill));
assert.ok(/snapshot|git (log|show|restore|checkout|revert|stash)/i.test(guide+'\n'+skill)||recovery.length,'app-03 UX: agent-facing instructions need a usable route to D5 recovery');
