import { fresh, log } from './harness';
import { readFileSync, existsSync, copyFileSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import assert from 'node:assert/strict';
const { addSource, reimportSource } = await import('../../packages/core/src/ingest/index');
const { sourceFile } = await import('../../packages/core/src/items');
const lib=fresh('original-assets');
const input=resolve('packages/core/test/fixtures/intake/files/saved-lesson/lesson.html');
const item=await addSource(lib,input); const original=sourceFile(item)!;
const html=readFileSync(original,'utf8');
const src=html.match(/<img[^>]+src="([^"]+)"/)![1]!;
assert(!src.includes(':'), 'Fixture uses a relative image');
const savedImage=item.body.match(/!\[[^\]]*\]\((assets\/[^)]+)\)/)![1]!;
const existsAtInput=existsSync(resolve(dirname(input),src));
if(process.argv.includes('--copy-relative')) copyFileSync(join(item.dir,savedImage),resolve(dirname(original),src));
const existsBesideOriginal=existsSync(resolve(dirname(original),src));
const r=await reimportSource(lib,item.meta.id);
log('original-assets',{htmlByteIdentical:readFileSync(input).equals(readFileSync(original)),relativeImage:src,existsAtInput,existsBesideOriginal,normalizedAssetExists:existsSync(join(item.dir,savedImage)),reimportPreservesDocImage:r.item.body.includes(savedImage)});
assert(existsBesideOriginal, 'Open original must resolve the saved HTML figure from the kept source folder (D122)');
