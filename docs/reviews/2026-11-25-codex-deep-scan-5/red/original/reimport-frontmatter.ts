import { fresh, log } from './harness';
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const { addSource, reimportSource, undoReimport } = await import('../../packages/core/src/ingest/index');
const { renameItem } = await import('../../packages/core/src/items');
const lib = fresh('reimport-frontmatter');
let served = 'Term,Meaning\nPractice,Repeat\n';
globalThis.fetch = (async () => new Response(served, { headers: {'content-type': 'text/csv'} })) as typeof fetch;
const item = await addSource(lib, 'https://original.invalid/frontmatter.csv');
const custom = '# My provenance\nmy_reference: "Chapter 7, library copy"\n';
writeFileSync(item.docPath, readFileSync(item.docPath, 'utf8').replace(/^---\n/, '---\n' + custom));
await renameItem(lib, item.meta.id, 'My chosen title');
assert(readFileSync(item.docPath, 'utf8').includes('my_reference:'), 'Known F607 rename control');
served += 'Recall,Retrieve\n';
const changed = await reimportSource(lib, item.meta.id);
const after = readFileSync(item.docPath, 'utf8');
await undoReimport(lib, item.meta.id, changed.step);
const undone = readFileSync(item.docPath, 'utf8');
log('custom-frontmatter', { changed: changed.changed, afterHasCustom: after.includes('my_reference'), undoHasCustom: undone.includes('my_reference'), titleKept: after.includes('My chosen title') });
assert(after.includes('my_reference:'), 'Reimport must preserve hand-written frontmatter outside its own metadata (F607)');
