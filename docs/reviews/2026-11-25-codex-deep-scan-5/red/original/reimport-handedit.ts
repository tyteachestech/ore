import { fresh, log } from './harness';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const { addSource, reimportSource } = await import('../../packages/core/src/ingest/index');
const { findItem } = await import('../../packages/core/src/items');
const { addHighlight, readAnnotations, anchorAnnotations } = await import('../../packages/core/src/annotations');
const lib = fresh('reimport-handedit');
const input = join(lib.root, 'lesson.csv');writeFileSync(input,'Topic,Advice\nSpacing,Wait before retrieving\n');
const item = await addSource(lib,input);
const extra = 'A personal example written into the document.';
writeFileSync(item.docPath,readFileSync(item.docPath,'utf8') + '\n' + extra + '\n');
const edited = findItem(lib,item.meta.id);
const hl=addHighlight(edited,{exact:extra,intent:'keep',note:'Remember this example.'});
if(process.argv.includes('--doctor')) await (await import('../../packages/core/src/doctor')).doctor(lib,{fix:true});
const r=await reimportSource(lib,item.meta.id);
const now=findItem(lib,item.meta.id);
log('handedit',{changed:r.changed,removed:r.removed.length,unplaced:r.unplaced.length,quoteInBody:now.body.includes(extra),highlightStillListed:readAnnotations(now).some(a=>a.id===hl.id),anchor:anchorAnnotations(now).find(a=>a.id===hl.id)?.anchor ?? null});
assert(r.removed.some(a=>a.id===hl.id), 'Reimport must report and remove an ordinary highlight whose hand-written passage it replaced (D93)');
