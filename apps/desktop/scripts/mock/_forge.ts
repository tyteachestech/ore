import { chromium } from "playwright";
const out = process.argv[2]!;
const b = await chromium.launch();
const p = await b.newPage({ deviceScaleFactor: 2, viewport: { width: 1280, height: 800 } });
p.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await p.addInitScript({ path: "apps/desktop/scripts/mock/tauri.js" });
await p.goto("http://localhost:1420/"); await p.waitForTimeout(1500);
await p.locator(".sidebar .side-item", { hasText: "Storytelling" }).first().click(); await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/1-skill.png` });
await p.locator(".try-now .try-check").click(); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/2-did.png` });
await p.keyboard.press("Escape");
await p.locator(".forge-door").click(); await p.waitForTimeout(600);
await p.locator(".forge-row[data-state=waiting]").first().hover();
await p.screenshot({ path: `${out}/3-forge.png` });
await p.locator(".forge-head .icon-btn").click(); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/4-add.png` });
await p.keyboard.press("Escape");
await p.locator(".forge-row[data-state=now] .forge-open").click(); await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/5-try.png` });
await p.locator(".try-go").click(); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/6-try-did.png` });
await b.close();
